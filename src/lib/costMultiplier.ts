/**
 * 计费倍率的上界。**必须与后端 `pricing::MAX_COST_MULTIPLIER` 同值**。
 *
 * 1000 的取法：中转站折扣实际区间是 0.1~5（常见 0.3、0.5、2），官方原价 1.0。
 * 留三个数量级余量已足够容纳任何真实定价，再大只可能是笔误
 * （少点一个小数点，或把「每百万 token 的价格」当倍率填了进来）。
 */
export const MAX_COST_MULTIPLIER = 1000;

/**
 * 计费倍率是否可用（空串 = 未填，合法）。
 *
 * # 为什么前端也要判
 *
 * 后端 `estimate_cost` 对非法值**静默退回 1.0**。那个兜底是对的（不能让一个笔误把整页金额
 * 算成 0），但它同时意味着用户填错时**界面上什么都不会说**：他填了「0.3折」「三折」「30%」，
 * 以为倍率生效了，用量页却按原价算 —— 而那正是他配这个字段要解决的问题。
 * 金额差 3 倍且无人告知，比压根不支持更糟。
 *
 * # 判据必须与后端逐条对齐
 *
 * 有限、正数、不超上界。任何一条不一致就会出现「前端放过、后端按 1.0 算」（用户以为生效了）
 * 或「前端拦下、后端本来能用」（凭空少一个能力）的错位。
 *
 * `"inf"` / `"1e400"` 都能被 `Number()` 解析成 `Infinity`，且 `Infinity > 0` 为真 ——
 * 必须靠 `Number.isFinite` 显式挡掉。后端那侧踩过同一个坑：`f64::INFINITY` 过了
 * `> 0.0` 那道门，把金额撑成 $18446744073。
 *
 * # 为什么从 KeyEditor 搬出来
 *
 * 它是一条**跨语言不变量**（与 Rust 侧同值），不是组件的私事。放在组件里意味着
 * 唯一能验证它的办法是渲染整个编辑器抽屉，于是实际上没有测试 ——
 * 而这恰恰是最该被钉住的那类逻辑。
 */
export function isValidCostMultiplier(raw: string): boolean {
  const s = raw.trim();
  if (!s) return true; // 未填 = 用官方原价
  const n = Number(s);
  return Number.isFinite(n) && n > 0 && n <= MAX_COST_MULTIPLIER;
}
