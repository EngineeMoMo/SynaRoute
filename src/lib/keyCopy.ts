import type { ProviderKey } from "@/types";

/**
 * 复制一条 Key 的配置，得到一份可以直接喂给 `KeyEditor` 的草稿。
 *
 * # 为什么需要它
 *
 * 同一个供应商常有多个 key（不同额度、不同账号），而它们的 `baseUrl` / 协议 / 模型列表 /
 * 映射 / 余额查询 / 计费倍率 全都一样 —— 用户原话是「新建太麻烦了」。
 * 真正需要换的只有密钥本身。
 *
 * # 🔴 必须用展开式（`...k`），不许改成逐字段列举
 *
 * 白名单式的失效方向是**静默**的：`ProviderKey` 日后加一个字段，复制时漏掉它，
 * 用户复制完发现某个设置没跟过来，而界面上没有任何提示。展开式相反 ——
 * 新字段默认跟着走，而「跟错了」只可能发生在下面这几个已知的运行态字段上。
 * 有一条逐字段对账的测试钉住这条（不是源码级 grep，那种判据太容易被写法绕过）。
 *
 * # 四项覆盖，各对应一个具体后果
 *
 * | 覆盖 | 不覆盖会怎样 |
 * |---|---|
 * | `id: ""` | 后端 `upsert_key` 按 id 认领 → **直接覆盖掉原 Key**，而用户以为自己在新增 |
 * | `hasSecret: false` | 密钥存在加密库里、前端只有这个布尔值 —— 带 true 会让编辑器显示「已配置，留空则不修改」，用户不填就保存 → config 说有密钥、库里没有，转发报「未配置密钥」且无对账路径 |
 * | `health` 归零 | 副本一挂出来就带着原 Key 的健康态/熔断计数/模型锁，而那是**另一条 Key 的**运行历史 |
 * | `name` 加后缀 | 两条同名 Key，列表里分不出谁是谁（名字允许重名，靠 id 唯一） |
 *
 * # `priority` 刻意不动
 *
 * 副本会与原 Key 撞同一个 priority，而后端 `upsert_key` 的**新插入**分支正是为此建的：
 * 撞了就顶到队尾（`max+1`）。那段注释原文写着「前端新建 Key 时恒发 999……
 * 判据放在**碰撞**而不是无条件重编号上」。这里靠它就够了，前端再猜一个数字只会两处打架。
 *
 * # `balanceQuery.apiKeyRef` 刻意保留
 *
 * 它的语义是「覆盖余额查询用的密钥库键名，留空 = 用本 Key 自己的密钥」。留空是常态
 * （→ 副本自动用副本自己的密钥）；用户显式填了某条 Key 的 id，那是「两条 Key 共用一个
 * 计费账号」的明确意图，复制时替他清掉才是错的。
 *
 * # 🔴 `id: ""` 还顺带决定了编辑器把它当「新建」
 *
 * `KeyEditor` 的 `isNew` 判据是 **`!initial?.id`** 而不是 `!initial` —— 就是为了这条路径。
 * 按 `!initial` 判的话：抽屉标题写「编辑 Key」（而它明明是新的一条），
 * 且会放过「拉模型前必须先填密钥」那道校验 —— 那时点「拉取」会拿一个空 id 去密钥库取，
 * 报出的是底层错误，不是就地可行动的「请先填密钥」。
 * 对原有两条路径行为完全不变：新建 `initial` 为 null → true；编辑时 id 非空 → false。
 * 有一条判据钉住那一行的形态。
 */
export function makeKeyCopy(k: ProviderKey, nameSuffix: string): ProviderKey {
  return {
    ...k,
    id: "",
    name: `${k.name}${nameSuffix}`,
    hasSecret: false,
    health: { status: "unknown", failCount: 0 },
  };
}
